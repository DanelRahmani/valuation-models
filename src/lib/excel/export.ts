import type ExcelJS from 'exceljs';
import { cellAddress, toExcel, type Fmt, type Values, type Workbook } from '../finance/calcsheet';
import type { AlignedReturns } from '../finance/capm';
import type { Historicals, LineItem } from '../finance/types';
import type { RunOutput } from '../finance/run';

const NUMFMT: Record<Fmt, string> = {
  usd: '"$"#,##0.00',
  usdm: '#,##0',
  pct: '0.0%',
  x: '0.0"x"',
  num: '0.0000',
  shares: '#,##0',
  beta: '0.00',
};

const MAROON = 'FF4A0E0E';
const CREME = 'FFFDFBF6';

const LABELS: Record<LineItem, string> = {
  revenue: 'Revenue',
  cogs: 'Cost of revenue',
  operatingIncome: 'Operating income',
  da: 'Depreciation & amortisation',
  interestExpense: 'Interest expense',
  pretaxIncome: 'Pre-tax income',
  taxExpense: 'Income tax',
  netIncome: 'Net income',
  cfo: 'Cash from operations',
  capex: 'Capital expenditure',
  dividendsPaid: 'Dividends paid',
  buybacks: 'Share buybacks',
  cash: 'Cash and equivalents',
  shortTermInvestments: 'Short-term investments',
  debtCurrent: 'Debt, current',
  debtNoncurrent: 'Debt, noncurrent',
  equity: 'Stockholders equity',
  sharesOutstanding: 'Shares outstanding',
  dilutedShares: 'Diluted shares (weighted)',
  sbc: 'Stock-based compensation',
};

function header(ws: ExcelJS.Worksheet, values: string[]) {
  const r = ws.getRow(1);
  values.forEach((v, i) => (r.getCell(i + 1).value = v));
  r.font = { bold: true, color: { argb: CREME } };
  r.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: MAROON } };
}

export async function exportWorkbook(
  ticker: string,
  h: Historicals,
  out: RunOutput,
  beta?: { aligned: AlignedReturns } | null,
): Promise<Blob> {
  const { default: Excel } = await import('exceljs');
  const wb: Workbook = out.wb;
  const v: Values = out.values;
  const book = new Excel.Workbook();
  book.creator = 'Valuation Models';
  book.created = new Date();

  /* About */
  const about = book.addWorksheet('About');
  about.getColumn(1).width = 110;
  [
    `${h.name} (${ticker}): valuation workbook`,
    'Generated by Valuation Models. Every model sheet is live: change a value on the Inputs sheet and the workbook recalculates.',
    'Monetary amounts are in $ millions and share counts in millions, except per-share values.',
    'Mathematical valuations under stated assumptions. Not investment advice.',
    'Data: SEC EDGAR XBRL company facts; market inputs as shown on the Inputs sheet with their sources.',
    out.reverse.growth != null
      ? `Reverse DCF: the price implies ${(out.reverse.growth * 100).toFixed(1)}% stage-1 revenue growth (solved by bisection; use Goal Seek on FCFF to confirm).`
      : `Reverse DCF: ${out.reverse.message}`,
    ...out.warnings.map((w) => `Note: ${w}`),
  ].forEach((t, i) => {
    about.getCell(i + 1, 1).value = t;
    if (i === 0) about.getCell(1, 1).font = { bold: true, size: 14, color: { argb: MAROON } };
  });

  /* Inputs, with one defined name per input */
  const inp = book.addWorksheet('Inputs');
  header(inp, ['Input', 'Value', 'Source', 'Name']);
  inp.columns = [{ width: 44 }, { width: 16 }, { width: 60 }, { width: 16 }];
  wb.inputs.forEach((d, i) => {
    const row = i + 2;
    const c = inp.getCell(row, 2);
    const result = v.inputs[d.key] ?? undefined;
    c.value = typeof d.value === 'string' ? { formula: toExcel(d.value, wb, undefined), result } : (d.value ?? null);
    c.numFmt = NUMFMT[d.fmt];
    inp.getCell(row, 1).value = d.label;
    inp.getCell(row, 3).value = d.source;
    inp.getCell(row, 4).value = d.key;
    if (typeof d.value !== 'string') c.font = { color: { argb: 'FF1F4E9A' } }; // blue = hard-coded input, banker convention
    book.definedNames.add(`Inputs!$B$${row}`, d.key);
  });

  /* Historicals */
  const hist = book.addWorksheet('Historicals');
  header(hist, ['$ millions', ...h.years.map((y) => `FY${y}`), 'XBRL tag (latest)']);
  hist.getColumn(1).width = 30;
  (Object.keys(LABELS) as LineItem[]).forEach((k, i) => {
    const arr = h.items[k] ?? [];
    const r = hist.getRow(i + 2);
    r.getCell(1).value = LABELS[k];
    arr.forEach((x, j) => {
      const c = r.getCell(j + 2);
      c.value = x ? x.value / 1e6 : null;
      c.numFmt = '#,##0';
    });
    r.getCell(h.years.length + 2).value = arr.at(-1)?.tag ?? 'missing';
  });

  /* Model sheets */
  for (const s of wb.sheets) {
    const ws = book.addWorksheet(s.name);
    header(ws, [s.title, ...s.columns]);
    ws.getColumn(1).width = 48;
    for (let c = 0; c < s.columns.length; c++) ws.getColumn(c + 2).width = 14;
    s.rows.forEach((r, i) => {
      const row = ws.getRow(i + 2);
      row.getCell(1).value = r.label;
      if (r.emphasis) row.font = { bold: true };
      r.cells.forEach((cell, c) => {
        if (cell == null) return;
        const target = row.getCell(c + 2);
        const result = v.sheets[s.name][r.key]?.[c] ?? undefined;
        target.value = typeof cell === 'string' ? { formula: toExcel(cell, wb, s), result } : cell;
        target.numFmt = NUMFMT[r.fmt];
      });
      if (r.note) row.getCell(1).note = r.note;
    });
    if (s.status !== 'ok') {
      const n = s.rows.length + 3;
      ws.getCell(n, 1).value = `Not applicable: ${s.message ?? ''}`;
      ws.getCell(n, 1).font = { italic: true, color: { argb: MAROON } };
    }
  }

  /* Summary */
  const sum = book.addWorksheet('Summary');
  header(sum, ['Model', 'Value per share', 'Status']);
  sum.columns = [{ width: 40 }, { width: 18 }, { width: 70 }];
  const summarySheets = wb.sheets.filter((s) => !s.id.startsWith('fcff_'));
  summarySheets.forEach((s, i) => {
    const r = sum.getRow(i + 2);
    r.getCell(1).value = s.title;
    if (s.status === 'ok') {
      const addr = cellAddress(s, s.result.row, s.result.col);
      r.getCell(2).value = { formula: `'${s.name}'!${addr}`, result: v.sheets[s.name][s.result.row]?.[s.result.col] ?? undefined };
      r.getCell(2).numFmt = NUMFMT.usd;
    }
    r.getCell(3).value = s.status === 'ok' ? '' : s.message ?? s.status;
  });
  const pr = summarySheets.length + 3;
  sum.getCell(pr, 1).value = 'Share price (reference, not a verdict)';
  sum.getCell(pr, 2).value = { formula: 'price', result: v.inputs.price ?? undefined };
  sum.getCell(pr, 2).numFmt = NUMFMT.usd;

  /* Sensitivity (values: Excel data tables cannot be written portably) */
  if (out.sensitivity) {
    const se = book.addWorksheet('Sensitivity');
    se.getCell(1, 1).value = 'FCFF value per share: WACC (rows) × terminal growth (columns). Values computed by the site.';
    out.sensitivity.growths.forEach((g, j) => {
      se.getCell(2, j + 2).value = g;
      se.getCell(2, j + 2).numFmt = NUMFMT.pct;
    });
    out.sensitivity.waccs.forEach((w, i) => {
      se.getCell(i + 3, 1).value = w;
      se.getCell(i + 3, 1).numFmt = NUMFMT.pct;
      out.sensitivity!.grid[i].forEach((x, j) => {
        se.getCell(i + 3, j + 2).value = x;
        se.getCell(i + 3, j + 2).numFmt = NUMFMT.usd;
      });
    });
  }

  /* Beta regression with live formulas (only when returns were uploaded) */
  if (beta) {
    const b = book.addWorksheet('Beta');
    header(b, ['Period', 'Stock return', 'Market return']);
    const a = beta.aligned;
    a.periods.forEach((p, i) => {
      b.getCell(i + 2, 1).value = p;
      b.getCell(i + 2, 2).value = a.stock[i];
      b.getCell(i + 2, 3).value = a.market[i];
      b.getCell(i + 2, 2).numFmt = b.getCell(i + 2, 3).numFmt = '0.00%';
    });
    const last = a.periods.length + 1;
    const rows: [string, string][] = [
      ['Beta (SLOPE)', `SLOPE(B2:B${last},C2:C${last})`],
      ['R² (RSQ)', `RSQ(B2:B${last},C2:C${last})`],
      ['Std error of regression (STEYX)', `STEYX(B2:B${last},C2:C${last})`],
      ['Std error of beta', `STEYX(B2:B${last},C2:C${last})/SQRT(DEVSQ(C2:C${last}))`],
      ['Blume-adjusted beta', `0.67*F2+0.33`],
    ];
    rows.forEach(([label, f], i) => {
      b.getCell(i + 2, 5).value = label;
      b.getCell(i + 2, 6).value = { formula: f };
      b.getCell(i + 2, 6).numFmt = '0.000';
    });
    b.getColumn(5).width = 34;
  }

  const buf = await book.xlsx.writeBuffer();
  return new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}
